def due(start, val, tmode):
    """按口径推算截止时刻。tmode ∈ work / natural / workdays。"""
    if tmode == "natural":
        return sop.deadline(start, val, work=None)
    if tmode == "workdays":
        return sop.workdays_after(start, val, work=WORK, holidays=HOLIDAYS)
    return sop.deadline(start, val, work=WORK, workdays_only=WORKDAYS_ONLY, holidays=HOLIDAYS)


