def md_section(c):
    d = E.due(c["start"], c["sla_hours"], c["tmode"])
    unit = ("%d 个工作日" % c["sla_hours"]) if c["tmode"] == "workdays" else ("%d 小时" % c["sla_hours"])
    L = ["## %s %s（情形：%s）" % (c["id"], c["name"], "、".join(c["cats"])), "",
         "| 项 | 值 |", "| --- | --- |",
         "| 负责岗位 | %s |" % c["role"],
         "| 协作岗位 | %s |" % ("、".join(c.get("support") or []) or "无"),
         "| 时限 | %s（口径 `%s`） |" % (unit, c["tmode"]),
         "| 时限说明 | %s |" % c["sla_desc"],
         "| 起算点 | %s |" % c["start"].strftime("%Y-%m-%d %H:%M"),
         "| 推算截止 | %s |" % d.strftime("%Y-%m-%d %H:%M"), "",
         "**必填输出**（%d 项）" % len(c["outputs"]), ""]
    L += ["- [ ] %s" % o for o in c["outputs"]]
    L += ["", "**完成检查项**（%d 条）" % len(c["checklist"]), ""]
    L += ["- [ ] %s" % k for k in c["checklist"]]
    L += ["", "结果：负责岗位 **%s** / 口径 **%s** / 时限 **%s** / 截止 **%s** / 必填输出 **%d** 项 / 检查项 **%d** 条"
          % (c["role"], c["tmode"], unit, d.strftime("%Y-%m-%dT%H:%M"),
             len(c["outputs"]), len(c["checklist"])), ""]
    return L
