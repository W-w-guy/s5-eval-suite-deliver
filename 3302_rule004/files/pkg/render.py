# -*- coding: utf-8 -*-
"""逐例 Markdown 渲染。"""
import engine as E
from kitlib import tables as T


def md_head():
    L = ["# 折扣审批路由表与 12 个越权审批场景（全部虚构）", "",
         "口径（均为虚构值）：", "",
         "```",
         "角色折扣上限：招商业务员 5.0% / 招商主管 10.0% / 运营总监 15.0% / 总经理 20.0%",
         "超出 = 折扣率 − 发起人上限；等于上限（超出 = 0）不需审批",
         "区间判定（左开右闭）：",
         "  0 < 超出 ≤ 5 个百分点  → R01 招商主管",
         "  5 < 超出 ≤ 10 个百分点 → R02 运营总监",
         "  超出 > 10 个百分点     → R03 总经理",
         "特殊条款路由：免押金 → R04 运营总监；延期付款 → R05 运营总监；免租期 > 30 天 → R06 总经理",
         "同时命中折扣与特殊条款：取层级更高的一条，不叠加串行",
         "审批人与发起人同角色：跳过该节点，从下一节点起",
         "节点超时：自动上升一级；任何情况下不允许自动通过",
         "中途修改报价：原审批作废，按新口径重新审批",
         "```", "",
         "> 百分点数值内部以「百分点 × 10」的整数参与运算（51 表示 5.1 个百分点），不使用浮点。",
         "> 企业、产品、角色人员均为虚构，不含真实客户信息。", ""]
    L += ["## 路由表（7 列）", ""]
    L += T.grid(["路由编号", "触发条件", "审批节点序列", "每节点时限（小时）",
                 "超时动作", "可否加签", "可否转交"],
                [[r["id"], r["cond"], " → ".join(r["chain"]),
                  "；".join("%s %d" % (n, E.NODE_HOURS[n]) for n in r["chain"]),
                  "提醒 + 自动上升一级（不允许自动通过）",
                  "可（加签仅限同级或更高层级）", "可（转交后时限不重置）"]
                 for r in E.ROUTES])
    L += ["", "未命中以上任一条件（折扣未超上限且无特殊条款）→ **不需审批，直接生效**。", ""]
    return L


def md_section(c):
    e = E.evaluate(c)
    L = ["## %s（情形：%s）" % (c["id"], "、".join(c["cats"])), "",
         "场景：%s。" % c["scene"], "",
         "**发起人与报价摘要**", "", "| 项 | 值 |", "| --- | --- |",
         "| 发起人角色 | %s（上限 %s%%） |" % (c["initiator"], E.pct(e["cap_x10"])),
         "| 产品 | %s |" % c["product"],
         "| 租期 | %d 个月 |" % c["months"],
         "| 折扣率 | %s%% |" % E.pct(c["disc_x10"]),
         "| 特殊条款 | %s |" % (c.get("clause") or "无")]
    if c.get("revised_x10") is not None:
        L += ["| 审批中途改后折扣 | %s%% |" % E.pct(c["revised_x10"])]
    if c.get("timeout"):
        L += ["| 节点超时 | 是（按路由表时限判超时） |"]
    if c.get("rejected"):
        L += ["| 上一轮结果 | 驳回，本次为重提 |"]
    L += ["", "**逐步判定**", ""]
    i = 1
    def n(t):
        nonlocal i
        L.append("%d. %s" % (i, t))
        i += 1
    n("超出百分点 = 折扣 %s − 上限 %s = **%s** 个百分点。"
      % (E.pct(c["disc_x10"]), E.pct(e["cap_x10"]), E.pct(max(e["excess_x10"], 0))
         if e["excess_x10"] >= 0 else "−" + E.pct(-e["excess_x10"])))
    if e["excess_x10"] <= 0:
        n("超出 ≤ 0 → **等于或低于上限，不需审批**。")
    else:
        n("按左开右闭落档：折扣路由 = **%s**。" % e["route_by_discount"])
    if c.get("clause"):
        n("特殊条款「%s」→ 条款路由 = **%s**。" % (c["clause"], e["route_by_clause"]))
        if e["route_by_discount"] not in ("无", e["route_by_clause"]):
            n("折扣路由与条款路由同时命中，取层级更高的一条 → **%s**。" % e["route"])
    n("命中路由：**%s**；期望审批链：**%s**。" % (e["route"], e["chain"]))
    if e["chain_len"]:
        n("链上各节点时限合计 = **%d 小时**。" % e["hours"])
    if c.get("revised_x10") is not None:
        n("审批中途改价 → 原审批作废，按 %s%% 重新走审批。" % E.pct(c["revised_x10"]))
    if c.get("timeout"):
        n("节点超时 → 自动上升一级，**不允许自动通过**。")
    if c.get("rejected"):
        n("上一轮驳回 → 本次重提，重新走同一路由。")
    L += ["", "**边界说明**：区间为左开右闭 —— 恰好等于上界（如超出恰好 5 个百分点）仍留在本档，",
          "只有**超过**上界才升档；折扣恰好等于角色上限（超出 = 0）不需审批。", "",
          "结果：路由 **%s** / 审批链 **%s** / 时限 **%d** 小时 / 期望结果 **%s**" % (
              e["route"], e["chain"], e["hours"], e["result"]), "",
          "备注：%s。" % e["note"], ""]
    return L
