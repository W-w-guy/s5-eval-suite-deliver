         "> 转接规则表见 `transfer_rules.csv` 与 `transfer_tables.xlsx`；",
         "> 处理流程图见 `transfer_flow.md`；知识缺口回写字段见 `knowledge_gap.md`。", "",
         "## 一、双时段响应时限（同一个时长，两种起算点）", "",
         "| 档位 | 时长 | 工作时间提出（工作日 9:00–18:00） | 非工作时间提出 |",
         "| --- | --- | --- | --- |",
