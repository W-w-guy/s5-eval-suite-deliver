    L += sop.matrix([dict(id=r["id"], name=r["trigger"][:18], role=r["role"], support=[])
                     for r in E.RULES], E.ROLES)
    L += ["", "R = 该规则的接手岗位。", ""]
    L += ["## 七、响应时限一览（8 个示例）", ""]
