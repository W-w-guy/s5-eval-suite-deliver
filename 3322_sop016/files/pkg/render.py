def md_section(c):
    e = E.evaluate(c)
    L = ["## %s（情形：%s）" % (c["id"], "、".join(c["cats"])), "",
         "场景：%s。" % c["scene"], "",
         "| 项 | 值 |", "| --- | --- |",
         "| 命中规则 | %s（%s） |" % (e["rule_id"], e["trigger"]),
         "| 接手岗位 | %s |" % e["role"],
         "| 档位 | %s（%s 分钟） |" % (e["tier"], int(round(e["sla_hours"] * 60))),
         "| 提出时刻 | %s |" % c["start"].strftime("%Y-%m-%d %H:%M"),
         "| 提出时段 | %s |" % ("工作时间" if e["shift"] == "work" else "非工作时间（夜间/周末/节假日）"),
         "| 响应截止 | %s |" % e["due"].replace("T", " "),
         "| 时限口径 | %s |" % e["shift_label"],
         "| 回写知识缺口 | %s |" % e["backwrite"],
         "| 超时升级 | %s |" % e["escalate"], "",
         "**处理步骤**", ""]
    i = 1
    def n(t):
        nonlocal i
        L.append("%d. %s" % (i, t)); i += 1
    n("管家会话中命中触发条件 → **%s**（%s）。" % (e["rule_id"], e["trigger"]))
    n("生成待办，指派给 **%s**，起算时刻 %s。" % (e["role"], c["start"].strftime("%H:%M")))
    if e["shift"] == "work":
        n("提出时刻在工作时间内 → 时长就地消耗，响应截止 **%s**。"
          % e["due"][11:].replace("T", ""))
    else:
        n("提出时刻在非工作时间 → 顺延到下一工作日 09:00 起算，响应截止 **%s**。"
          % e["due"][:16].replace("T", " "))
    if c["id"] == "P08":
        n("到达截止仍未响应 → 一级升级到**值班主管**；再审未响应则升客服负责人。")
    n("回写知识缺口：**%s**。" % ("必须（处理完成后 1 个工作日内由接手岗位提交）"
                             if e["backwrite"] == "是" else "本条规则无需回写"))
    L += ["", "结果：规则 **%s** / 岗位 **%s** / 档位 **%s** / 响应截止 **%s** / 回写 **%s**"
          % (e["rule_id"], e["role"], e["tier"], e["due"], e["backwrite"]), ""]
    return L
