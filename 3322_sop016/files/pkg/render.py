         "> 「非工作时间」= 工作日 18:00–次日 09:00、周六周日、节假日。",
         "> 实现上只用一个口径：**时长只在工作日 09:00–18:00 内消耗**，非工作时间自动顺延。",
         "> 因此夜间与周末不必各写一条分支，也就不会出现「夜间忘写时限」这类漏洞。",
         "> 紧急档用于：涉及**他人信息**、涉及**合同承诺**——这两类不得按普通档排。", "",
